const { test } = require('node:test');
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { Pool } = require('pg');
const { assertIsolatedTestDatabase } = require('./test-database');

test('one physical product supports independent channel listings and prices', { skip: !process.env.TEST_DATABASE_URL }, async t => {
  const url = assertIsolatedTestDatabase();
  const admin = new Pool({ connectionString: url.toString() });
  const dbModule = require('../db-pool');
  const original = dbModule.createPool;
  dbModule.createPool = (connectionString, options) => new Pool({ connectionString, ...options, options:'-c search_path=alsvid_v2' });
  delete require.cache[require.resolve('../storefront-listings')];
  const { createStorefrontListingStore } = require('../storefront-listings');
  dbModule.createPool = original;
  let store;
  t.after(async()=>{if(store)await store.close();await admin.end()});
  await admin.query(`CREATE SCHEMA alsvid_v2;
    CREATE FUNCTION alsvid_v2.generate_uuid_v7() RETURNS uuid LANGUAGE sql AS $$ SELECT gen_random_uuid() $$;
    CREATE TABLE alsvid_v2.products(id text PRIMARY KEY,entity_uuid uuid UNIQUE NOT NULL,status text NOT NULL,specs jsonb NOT NULL);
    CREATE TABLE alsvid_v2.skus(entity_uuid uuid PRIMARY KEY,product_uuid uuid NOT NULL REFERENCES alsvid_v2.products(entity_uuid),code text UNIQUE NOT NULL);
    CREATE TABLE alsvid_v2.product_media(id text PRIMARY KEY,product_id text NOT NULL,content_type text NOT NULL);
    CREATE TABLE alsvid_v2.audit_log(actor text,action text,target text,before_json jsonb,after_json jsonb);
    CREATE TABLE alsvid_v2.catalog_publications(product_uuid uuid PRIMARY KEY,draft jsonb NOT NULL,published jsonb,revision integer NOT NULL,published_revision integer,legacy_product_market jsonb);
    CREATE TABLE alsvid_v2.storefront_offers(sku_uuid uuid,currency text,unit_price numeric,published boolean,revision integer);
    INSERT INTO alsvid_v2.products VALUES('a','00000000-0000-4000-8000-000000000001','启用','{"motor":"250W"}'),('b','00000000-0000-4000-8000-000000000002','启用','{}');
    INSERT INTO alsvid_v2.skus VALUES('10000000-0000-4000-8000-000000000001','00000000-0000-4000-8000-000000000001','A1-EBI-450-BLK'),('10000000-0000-4000-8000-000000000002','00000000-0000-4000-8000-000000000002','B1-EBI-450-BLK');`);
  await admin.query(readFileSync(path.join(__dirname,'../migrations/082_storefront_listings.sql'),'utf8'));
  store=createStorefrontListingStore(url.toString());
  const document=(title,slug)=>({model:'A1',languages:{de:{title,description:'',specifications:[]}},mediaIds:[],seo:{slug,title:'',description:'',keywords:'',canonical:''}});
  const sku=(price)=>[{sku:'A1-EBI-450-BLK',prices:[{currency:'EUR',unitPrice:price,published:true}]}];
  const first=await store.create({productId:'a',channel:'website',document:document('Site title','a1'),skus:sku('1299')});
  const second=await store.create({productId:'a',channel:'marketplace',document:document('Channel title','a1'),skus:sku('1499')});
  const rows=await store.list('a');
  assert.equal(rows.length,2);
  assert.equal(rows.find(row=>row.id===first.id).draft.languages.de.title,'Site title');
  assert.equal(rows.find(row=>row.id===second.id).skus[0].prices[0].unitPrice,'1499.00');
  await assert.rejects(store.create({productId:'a',channel:'website',document:document('Duplicate','a1'),skus:sku('1')}),/URL 别名已存在/);
  await assert.rejects(store.create({productId:'a',channel:'other',document:document('Wrong SKU','other'),skus:[{sku:'B1-EBI-450-BLK',prices:[]}]}),/SKU 不属于/);
  const published=await store.publish(first.id,{revision:first.revision});
  await assert.rejects(store.update(first.id,{revision:published.revision,channel:'website',document:document('Changed','a1'),skus:sku('1')}),/先下架/);
  assert.deepEqual((await admin.query("SELECT specs FROM alsvid_v2.products WHERE id='a'")).rows[0].specs,{motor:'250W'});
});
